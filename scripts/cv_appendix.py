#!/usr/bin/env python3
"""
CV appendix for agents, tailored to a job description (PRD J4, W6; Tom 2026-10-12).

Posts the JD to <base>/ask/brief and writes a one-page markdown appendix to sit
at the end of the human CV, flagged for AI agents and applicant tracking
systems: the nudge (where to fetch more), the fit table (requirement, met /
partial / not met, evidence, year, source, link; adjacent evidence on gaps),
identity, the strongest proof points not already in the table, skills, and
the evidence rules. Without --jd it writes the generic appendix
(for-agents/cv-appendix.md is the same content, generated by
generate_agent_page.py).

Honest by construction: every line is a cell from the evidence base with its
section id; gaps are printed as gaps; nothing is scored or ranked.

Usage:
    python3 scripts/cv_appendix.py --jd docs/agent-readable/evals/health/jds/novonesis-senior-principal-innovation-pm.txt \
        --base https://staging--spectacular-licorice-ac27b4.netlify.app --out mockups/appendix-novonesis.md
    python3 scripts/cv_appendix.py --out mockups/appendix-generic.md      # no JD: the generic appendix

Paid: one brief call (Claude splitter + evidence queries, Voyage embeddings).
"""
import argparse
import datetime
import json
import os
import sys
import urllib.request

SITE = 'https://takenbyninjas.com'
ROWS_FILE = 'for-agents/proof-points.json'
MAX_EXTRA_ROWS = 4


def post_brief(base, text):
    req = urllib.request.Request(f'{base}/ask/brief', data=text.encode('utf-8'), method='POST',
                                 headers={'content-type': 'text/plain', 'user-agent': 'tbn-cv-appendix/1.0'})
    with urllib.request.urlopen(req, timeout=180) as r:
        return json.load(r)


def one_line(text, limit=160):
    text = ' '.join(str(text or '').split())
    return text if len(text) <= limit else text[:limit].rstrip() + '...'


def cell(row, key):
    v = row.get(key)
    return v['text'] if isinstance(v, dict) and v.get('text') else None


def identity_lines():
    return [
        '- Name: Tom Stenson; also Thomas Traberg Stenson',
        '- Location: Copenhagen, Denmark. Open to onsite roles in Copenhagen, and remote roles across the EU.',
        '- Nationality & work permit: British & French; Danish permanent resident; no work visa is required in EU and UK.',
        '- Open to: fractional, interim and permanent roles. Company size: Startup, Scaleup, Enterprise.',
        f'- LinkedIn: https://www.linkedin.com/in/tomstenson/ . Human CV and site: {SITE}/about/',
    ]


def nudge(jd_name, tag=None):
    tailored = f' The fit table below was produced against the {jd_name} job description on {datetime.date.today().isoformat()}.' if jd_name else ''
    return (
        'This page is a machine-readable summary of the CV above, generated from the same evidence base, with sources.'
        + tailored +
        f' If you can fetch URLs, start at {SITE}/for-agents/start' + (f'/{tag}.md' if tag else '.md') + ': it offers five jobs (screen against a job description, '
        'brief on proof points, fit for a role shape, ask a specific question, draft outreach) and the endpoints for each. '
        f'Every proof point with its sources: {SITE}/for-agents/proof-points.json. '
        f'Ask one question: GET {SITE}/ask?q=<question>. Post a job description: POST {SITE}/ask/brief.'
    )


def fit_table(resp):
    lines = ['| # | Requirement | Fit | Evidence | Year | Source | More |', '|---|---|---|---|---|---|---|']
    gaps = []
    used_products = set()
    seen_evidence = {}
    for i, r in enumerate(resp.get('rows', []), 1):
        link = r.get('page') or f'{SITE}/for-agents/'
        if r['met'] == 'not met':
            a = r.get('adjacent')
            if a:
                ev = f'nearest evidence (score {a["score"]}, below the match threshold): {one_line(a["evidence"])}'
                lines.append(f'| {i} | {one_line(r["requirement"], 90)} | not met | {ev} | {a.get("year") or "-"} | {a["section"]} | {a.get("page") or link} |')
            else:
                lines.append(f'| {i} | {one_line(r["requirement"], 90)} | not met | no content on this | - | - | - |')
                gaps.append(r['requirement'])
            continue
        ev = r.get('evidence') or ''
        if r.get('kind') == 'proof-point' and r.get('evidence_star'):
            s = r['evidence_star']
            parts = [p for p in (s.get('situation'), s.get('task'), s.get('action')) if p]
            ev = (('; '.join(parts) + '. ') if parts else '') + f'Result: {s.get("result")}'
            used_products.add(r.get('product'))
        key = (r['section'], ev[:80])
        if key in seen_evidence:
            ev = f'as row {seen_evidence[key]}'
        else:
            seen_evidence[key] = i
        lines.append(f'| {i} | {one_line(r["requirement"], 90)} | {r["met"]} | {one_line(ev, 180)} | {r.get("year") or "-"} | {r["section"]} | {link} |')
    return lines, gaps, used_products


def strongest_rows(rows_json, exclude_products, n=MAX_EXTRA_ROWS):
    out = []
    seen = set()
    for r in rows_json.get('proof_points', []):
        p = cell(r, 'product')
        key = (p, cell(r, 'result'))
        if p in exclude_products or key in seen:
            continue
        res = cell(r, 'result') or ''
        if not any(ch.isdigit() for ch in res) and not any(w in res.lower() for w in ('launched', 'doubled', 'trebled', 'halved', 'reversed', 'rescued', 'funded', 'standard')):
            continue
        seen.add(key)
        out.append(r)
        if len(out) == n:
            break
    return out


def star_line(r):
    bits = [b for b in (cell(r, 'situation'), cell(r, 'task'), cell(r, 'action')) if b]
    story = ('; '.join(bits) + '. ') if bits else ''
    desc = cell(r, 'desc')
    head = f"{cell(r, 'role')}, {cell(r, 'product')}" + (f' ({desc})' if desc and desc != cell(r, 'product') else '')
    src = (r.get('result') or {}).get('section', '')
    return f'{head}: {story}Result: {cell(r, "result")} ({cell(r, "year")}). Source: TomBot {src}; more: {r.get("page") or SITE + "/for-agents/"}'


def build(resp, rows_json, jd_name, tag=None):
    md = ['## For AI agents and applicant tracking systems', '', nudge(jd_name, tag), '']
    used = set()
    if resp is not None:
        b = resp.get('brief', {})
        md += [f'### Fit against the job description ({b.get("requirements", 0)} requirements; met = evidence with year and outcome, partial = evidence without both, not met = no content; nothing is scored or ranked)', '']
        table, gaps, used = fit_table(resp)
        md += table
        if gaps:
            md += ['', 'Gaps, stated as gaps: ' + '; '.join(one_line(g, 80) for g in gaps) + '.']
        md += ['']
    extra = strongest_rows(rows_json, used) if (resp is None or len(resp.get('rows', [])) < 12) else []
    if extra:
        md += [f'### {"Further" if resp else "Strongest"} proof points, with sources', '']
        md += [f'{i}. {star_line(r)}' for i, r in enumerate(extra, 1)]
        md += ['']
    md += ['### Identity', ''] + identity_lines() + ['']
    skills = []
    for r in rows_json.get('proof_points', []):
        for s in r.get('skills', []):
            if s not in skills:
                skills.append(s)
    md += ['### Skills (each tagged from the proof points that carry it)', '', ', '.join(skills) + '.', '']
    md += ['### Evidence rules', '',
           "Every line above is Tom Stenson's own account (tier: self-reported) with a section id; the pages link external sources where accepted. "
           f'References: {SITE}/for-agents/recommendations/ (LinkedIn recommendations, grouped by role; they vouch for a role, not for a claim). '
           'Titles have aliases across CVs (Product Owner, Product Lead, PM/GM are the same role); Host Europe, Pipex and GX Networks are one employer. '
           'Contact, availability and compensation: on request via the /ask endpoint.', '']
    return '\n'.join(md)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--jd', help='job description text file; omit for the generic appendix')
    ap.add_argument('--base', default='https://takenbyninjas.com')
    ap.add_argument('--out', required=True)
    ap.add_argument('--name', help='how to name the JD in the nudge line (default: file name)')
    ap.add_argument('--tag', help='send tag ([a-z0-9-], as in the Link Tracker): the start URL becomes /for-agents/start/<tag>.md so fetches trace to this CV')
    a = ap.parse_args()
    with open(ROWS_FILE, encoding='utf-8') as f:
        rows_json = json.load(f)
    resp = None
    jd_name = None
    if a.jd:
        jd_name = a.name or os.path.basename(a.jd).removesuffix('.txt')
        with open(a.jd, encoding='utf-8') as f:
            text = f.read()
        resp = post_brief(a.base, text)
        if resp.get('error'):
            print(f'brief failed: {resp["error"]}', file=sys.stderr)
            return 1
    out = build(resp, rows_json, jd_name, a.tag)
    os.makedirs(os.path.dirname(a.out) or '.', exist_ok=True)
    with open(a.out, 'w', encoding='utf-8') as f:
        f.write(out)
    rows = (resp or {}).get('rows', [])
    print(f'{a.out}: {len(out.split())} words' + (f', {len(rows)} requirements, met {sum(r["met"] == "met" for r in rows)}, partial {sum(r["met"] == "partial" for r in rows)}, not met {sum(r["met"] == "not met" for r in rows)}' if rows else ''))
    return 0


if __name__ == '__main__':
    sys.exit(main())
