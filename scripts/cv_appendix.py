#!/usr/bin/env python3
"""
CV appendix for agents, tailored to a job description (PRD J4, W6; Tom 2026-10-12).

Posts the JD to <base>/ask/brief and writes a one-page markdown appendix to sit
at the end of the human CV, flagged for AI agents and applicant tracking
systems: the nudge (where to fetch more), the fit table (requirement, met /
partial / not met, evidence, year, source, link; adjacent evidence on gaps),
identity, the strongest proof points not already in the table, skills, and
the evidence rules. Without --jd it writes the generic appendix
(for-agents/cv-appendix.md is the same content, generated by
generate_agent_page.py).

Honest by construction: every line is a cell from the evidence base with its
section id; gaps are printed as gaps; nothing is scored or ranked.

Usage:
    python3 scripts/cv_appendix.py --jd docs/agent-readable/evals/health/jds/novonesis-senior-principal-innovation-pm.txt \
        --base https://staging--spectacular-licorice-ac27b4.netlify.app --out mockups/appendix-novonesis.md
    python3 scripts/cv_appendix.py --out mockups/appendix-generic.md      # no JD: the generic appendix

Paid: one brief call (Claude splitter + evidence queries, Voyage embeddings).
"""
import argparse
import datetime
import json
import os
import re
import sys
import urllib.request

SITE = 'https://takenbyninjas.com'
ROWS_FILE = 'for-agents/proof-points.json'
MAX_EXTRA_ROWS = 4


def post_brief(base, text):
    req = urllib.request.Request(f'{base}/ask/brief', data=text.encode('utf-8'), method='POST',
                                 headers={'content-type': 'text/plain', 'user-agent': 'tbn-cv-appendix/1.0'})
    with urllib.request.urlopen(req, timeout=180) as r:
        return json.load(r)


def one_line(text, limit=160):
    text = ' '.join(str(text or '').split())
    return text if len(text) <= limit else text[:limit].rstrip() + '...'


def cell(row, key):
    v = row.get(key)
    return v['text'] if isinstance(v, dict) and v.get('text') else None


# Screening facts (R1012-22): read from the register the generator publishes in
# proof-points.json (`screening_facts`); nothing about Tom is typed here.
OMIT_ON_SEND = ('employment_type',)   # an application is for one role: say which, unless the JD asks


def classify_knockout(requirement, facts, max_chars=160):
    """The fact a JD line asks about (same patterns /ask/brief uses), or None."""
    text = ' '.join(str(requirement or '').split())
    if not text or len(text) > max_chars:
        return None
    for f in facts:
        if any(re.search(a, text, re.I) for a in f.get('asks', [])):
            return f
    return None


def screening_facts(facts, asks=None, answers=None, applying=None):
    """One line per fact: the standing value; what this job asks, in its words;
    Tom's answer for this job where he has given one. Returns (lines, open):
    `open` are the questions only Tom can settle, to ask him there and then."""
    asks, answers = asks or {}, answers or {}
    lines, open_q = [], []
    for f in facts:
        t, asked, answer = f['type'], asks.get(f['type']), answers.get(f['type'])
        if (not f['value'] or f.get('on_request')) and not asked and not answer:
            continue
        if applying and t in OMIT_ON_SEND and not asked:
            continue
        # Answer what was asked, nothing else: with no JD the whole fact; on a send
        # the core, plus only the qualifiers the JD line asks about; Tom's own
        # answer for this job replaces the qualifiers.
        if not applying and not asked and not answer:
            said = f['value']
        elif asked and not answer:
            said = '; '.join([f['base']] + [q['text'] for q in f.get('qualifiers', []) if re.search(q['ask'], asked, re.I)]) if f['base'] else None
        else:
            said = f['base']
        # The ask is not echoed (Tom, 2026-10-12): the reader has the JD; the line
        # only has to address it. Tom's answer names what was asked where it matters.
        line = f"- {f['label']}: {(said or 'not stated').rstrip('.')}"
        if answer:   # Tom's answer stands alone where the record has nothing: never "not stated; <answer>"
            line = f"- {f['label']}: " + '; '.join(x for x in (('' if f.get('on_request') else said or '').rstrip('.'), answer) if x)
        elif asked and (f.get('per_send') or not f['value'] or f.get('on_request')):
            open_q.append({'type': t, 'asked': asked, 'record': f['value']})
        lines.append(line)
        if t == 'name' and applying:
            lines.append(f'- Applying for: {applying}')
    lines.append('- LinkedIn: https://www.linkedin.com/in/tomstenson/')
    return lines, open_q


def nudge(jd_name, tag=None):
    # The HTML entry page, not start.md: ChatGPT's reader rejects .md URLs (paste-test run 2).
    start = f'{SITE}/for-agents/start/' + (f'{tag}/' if tag else '')
    against = f', against the job description for {jd_name}' if jd_name else ''
    # Tom's wording (2026-10-13).
    return (
        "This page is designed for machines. It has been generated by Tom Stenson's agent for recruiters' agents and screening tools "
        f"on {datetime.date.today().isoformat()}{against}. Query Tom's work agent direct at {start}"
    )


def _norm(t):
    return ' '.join(str(t or '').split()).lower()


def star_index(rows_json):
    """Find the local STAR row (tightened cells) for a brief row: by its result,
    verbatim or tightened; and the one row that summarises a section, if exactly one does."""
    by_result, by_section = {}, {}
    for r in rows_json.get('proof_points', []):
        res = r.get('result') or {}
        for t in (res.get('text'), res.get('quote')):
            if t:
                by_result[_norm(t)] = r
        if res.get('section'):
            by_section.setdefault(res['section'], []).append(r)
    return by_result, {k: v[0] for k, v in by_section.items() if len(v) == 1}


def star_of(r):
    return {k: cell(r, k) for k in ('situation', 'task', 'action', 'result') if cell(r, k)}


def who_of(r):
    return ', '.join(x for x in (cell(r, 'role'), cell(r, 'product'), year_span([cell(r, 'year')])) if x)


def fit_rows(resp, rows_json):
    """One dict per requirement, written by an agent for an agent: no first-person
    prose (Tom, 2026-10-12: the prose is the CV's job). A STAR row gives its
    tightened cells; a requirement a screener decides yes/no gives the fact; a
    section with no summarised story gives a pointer and a link; a gap says so."""
    by_result, by_section = star_index(rows_json)
    facts = rows_json.get('screening_facts', [])
    out, gaps, used_products, seen = [], [], set(), {}
    for i, r in enumerate(resp.get('rows', []), 1):
        row = {'n': i, 'requirement': ' '.join(str(r['requirement']).split()), 'fit': r['met'], 'star': None, 'fact': None, 'pointer': False,
               'nearest': None, 'same_as': None, 'who': None, 'section': r.get('section'), 'link': r.get('page')}
        if r['met'] == 'not met' and not classify_knockout(r['requirement'], facts):
            a = r.get('adjacent') or {}
            near = (by_result.get(_norm(a['evidence'])) or by_section.get(a.get('section'))) if a.get('evidence') else None
            if near:
                row.update(nearest=cell(near, 'result'), who=who_of(near), section=a.get('section'), link=near.get('page'), near=near)
            else:
                row.update(section=None, link=None)
                gaps.append(r['requirement'])
            out.append(row)
            continue
        if r.get('kind') == 'coverage':
            # Role coverage (2026-10-13): every role that matches a domain, an environment
            # or a level, in Tom's words, then the example stories the brief gave.
            row.update(coverage=r['evidence'], link=None,
                       also=[x for x in (by_result.get(_norm(o.get('evidence'))) for o in (r.get('also') or [])) if x])
            out.append(row)
            continue
        local = None
        if r.get('kind') == 'proof-point' and r.get('evidence_star'):
            local = by_result.get(_norm(r['evidence_star'].get('result')))
        fact = classify_knockout(r['requirement'], facts)
        if r.get('kind') == 'fact' or fact:
            # every fact the line asks (N1012-15); `fact` stays the first
            row.update(fit='fact', fact=r.get('fact_type') or fact['type'], facts=r.get('fact_types') or [r.get('fact_type') or fact['type']], link=None)
            out.append(row)
            continue
        local = local or by_section.get(r['section'])
        key = (cell(local, 'product'), cell(local, 'result')) if local else (r['section'], None)
        if key in seen:
            row['same_as'] = seen[key]
        else:
            seen[key] = i
        # A second example (R1012-23): further STAR rows the brief matched, other products only.
        row['also'] = [x for x in (by_result.get(_norm(o.get('evidence'))) for o in (r.get('also') or [])) if x and x is not local][:1]
        if local:
            row.update(star=star_of(local), who=who_of(local), link=local.get('page') or row['link'], local=local)
            used_products.add(cell(local, 'product'))
            # The story facet that matched (R1013-2) is carried by the brief row; the
            # appendix is itself Tom's CV material, so no facet source line is printed
            # (and a facet's CV of origin names a recipient company: never published).
        else:
            row['pointer'] = True
        out.append(row)
    return out, gaps, used_products


STAR_LABELS = (('situation', 'Situation'), ('task', 'Task'), ('action', 'Action'), ('result', 'Result'))


def first_sentence(text, limit=170):
    text = ' '.join(str(text or '').split())
    for stop in ('. ', '? ', '! '):
        k = text.find(stop)
        if 20 < k < limit:
            return text[:k + 1]
    return one_line(text, limit)


def end(text):
    text = str(text).strip()
    return text if text[-1:] in '.!?' else text + '.'


def fit_plain(rows, section_pages):
    """The appendix form. The foundation reader is the standard ATS (Tom,
    2026-10-12): it extracts text and matches words, nothing more. So: plain
    sentences, no tables, no arrays, no ids to resolve; each requirement in the
    job description's full words, its evidence beside it, every line complete on
    its own. Arrays and JSON are for agents, and live behind the link."""
    md = []
    for r in rows:
        link = r['link'] or section_pages.get(r['section'])
        stories = ([r['local']] if r.get('local') else []) + list(r.get('also') or [])
        if r.get('coverage'):
            said = end(r['coverage']) + ''.join(f" Example: {end(cell(x, 'result'))} {who_of(x)}." for x in stories)
        elif stories:
            first = stories[0]
            # A story already told above is restated short (result, who, when): no "see 1".
            cells = ('result',) if r['same_as'] else ('result', 'action')
            said = ' '.join(end(cell(first, k)) for k in cells if cell(first, k)) + f' {who_of(first)}.'
            said += ''.join(f" Also: {end(cell(x, 'result'))} {who_of(x)}." for x in stories[1:])
            said += f" {first.get('page') or link or SITE + '/for-agents/'}"
        elif r['pointer']:
            said = f"On record, no summarised story yet. {link or SITE + '/for-agents/'}"
        elif r.get('near'):
            said = f"Nearest, not a match: {end(cell(r['near'], 'result'))} {who_of(r['near'])}. {r['near'].get('page') or SITE + '/for-agents/'}"
        else:
            said = 'Not on record.'
        md += [f"{r['n']}. {end(r['requirement'])}", f"Evidence ({r['fit']}): {said}", '']
    return md


def year_span(texts):
    import re
    ys = [int(y) for t in texts for y in re.findall(r'(?:19|20)\d\d', t or '')]
    return f'{min(ys)}-{max(ys)}' if ys and min(ys) != max(ys) else (str(ys[0]) if ys else '')


def experience_by_area(rows_json, only=None):
    """Where each kind of work happened, for a screener doing tenure arithmetic:
    per role shape, the employers and the span of the stories there, linked to
    the shape page. Derived from the rows; no total is claimed."""
    out = []
    # Tom's own count first (R1013-13): the spans below are where the stories
    # sit, not years to add up.
    yrs = next((f for f in rows_json.get('screening_facts', []) if f.get('type') == 'years'), None)
    if yrs and yrs.get('value'):
        out.append(f"- Tom's own count: {yrs['value']}. The spans below are where the stories sit, not years to add up.")
    for sh in rows_json.get('shapes', []):
        by_co = {}
        for r in rows_json.get('proof_points', []):
            if sh['id'] in r.get('shapes', []):
                by_co.setdefault(r.get('company') or cell(r, 'role'), []).append(cell(r, 'year'))
        if not by_co or (only is not None and sh['id'] not in only):
            continue
        spans = sorted(((year_span(v), k) for k, v in by_co.items()), reverse=True)
        out.append(f"- {sh['label']}: " + '; '.join(f'{k} {v}' for v, k in spans) + f". {SITE}/for-agents/stories/#shape-{sh['id']}")
    return out


def load_section_pages():
    """Section id -> the story page that carries it (from the generator's page list)."""
    try:
        sys.path.insert(0, os.getcwd())
        from generate_agent_page import PAGES
        return {sec: f"{SITE}/for-agents/{p['slug']}/#{sec.lower().replace('.', '-')}" for p in PAGES for sec in p.get('sections', [])}
    except Exception as e:
        print(f'section pages unavailable ({e}); section rows link the facts page', file=sys.stderr)
        return {}


def strongest_rows(rows_json, exclude_products, n=MAX_EXTRA_ROWS):
    out = []
    seen = set()
    for r in rows_json.get('proof_points', []):
        p = cell(r, 'product')
        key = (p, cell(r, 'result'))
        if p in exclude_products or key in seen:
            continue
        res = cell(r, 'result') or ''
        if not any(ch.isdigit() for ch in res) and not any(w in res.lower() for w in ('launched', 'doubled', 'trebled', 'halved', 'reversed', 'rescued', 'funded', 'standard')):
            continue
        seen.add(key)
        out.append(r)
        if len(out) == n:
            break
    return out


def star_line(r):
    did = ' '.join(end(cell(r, k)) for k in ('result', 'action') if cell(r, k))
    return f"{did} {who_of(r)}. {r.get('page') or SITE + '/for-agents/'}"


def experience_rows(rows):
    """The fit rows without the fact requirements, renumbered (and "as N" with them)."""
    kept = [r for r in rows if r['fit'] != 'fact']
    renum = {r['n']: i for i, r in enumerate(kept, 1)}
    return [{**r, 'n': renum[r['n']], 'same_as': renum.get(r['same_as'])} for r in kept]


def build(resp, rows_json, jd_name, tag=None, applying=None, answers=None):
    md = ['## For AI agents and applicant tracking systems', '', nudge(jd_name, tag), '']
    rows, gaps, used = fit_rows(resp, rows_json) if resp is not None else ([], [], set())
    asks = {t: r['requirement'] for r in rows if r['fit'] == 'fact' for t in r.get('facts') or [r['fact']]}
    facts_md, open_q = screening_facts(rows_json.get('screening_facts', []), asks, answers, applying)
    md += ['### Screening facts', ''] + facts_md + ['']
    # On a send, summarise: only the areas and skills of the stories this fit uses.
    mine = [r for r in rows_json.get('proof_points', []) if cell(r, 'product') in used] if resp is not None else None
    # Years per area stay off the page until Tom rules on the spans; one link stands in.
    md[-2:-2] = [f'- Experience by area, with the stories for each: {SITE}/for-agents/stories/']
    if resp is not None:
        exp = experience_rows(rows)
        md += [f'### Fit: {jd_name} ({len(exp)} experience requirements, in the job description\'s words)', '']
        md += ['met = a story with an outcome and a date; partial = on record without both; not met = not on record.', '']
        md += fit_plain(exp, load_section_pages())
        if gaps:
            md += ['Not on record, ask Tom: ' + '; '.join(one_line(g, 80).rstrip('.') for g in gaps) + '.']
        md += ['']
    extra = strongest_rows(rows_json, used) if (resp is None or len(resp.get('rows', [])) < 12) else []
    if extra:
        md += [f'### {"Further" if resp else "Strongest"} results (result, action, role, product, years, link)', '']
        md += [f'{i}. {star_line(r)}' for i, r in enumerate(extra, 1)]
        md += ['']
    skills = []
    for r in (mine or rows_json.get('proof_points', [])):
        for s in r.get('skills', []):
            if s not in skills:
                skills.append(s)
    # Each skill links the page of stories that carry it: the words stay text for a
    # keyword pass, the link takes a reader (and a tracked click) to the evidence.
    md += ['### Skills', '', ', '.join(skills) + f". Every story that carries a skill: {rows_json.get('skills_index', SITE + '/for-agents/stories/#skills')}", '']
    md += ['### Notes', '',
           f"- Source: Tom Stenson's own record (self-reported), summarised by his agent. References by role: {SITE}/for-agents/recommendations/",
           f'- Contact, availability, compensation: on request, {SITE}/ask?q=How%20can%20I%20contact%20Tom%3F', '']
    return '\n'.join(md), open_q


SENDS_FILE = 'for-agents/sends.json'


def record_send(tag, role, company, jd_name, answers=None):
    """Register the send (item 231, narrowed 2026-10-19): sends.json maps the tag to the role
    and company so the tagged entry file can name them. No per-send page: a page can be
    public (and disclose the application) or noindex (and invisible to Copilot), never useful."""
    sends = {'sends': {}}
    if os.path.exists(SENDS_FILE):
        with open(SENDS_FILE, encoding='utf-8') as f:
            sends = json.load(f)
    sends['sends'][tag] = {'role': role, 'company': company, 'jd': jd_name, 'date': datetime.date.today().isoformat(),
                           'answers': answers}
    with open(SENDS_FILE, 'w', encoding='utf-8') as f:
        json.dump(sends, f, ensure_ascii=False, indent=2)
        f.write('\n')
    print(f'send recorded in {SENDS_FILE}: {tag} -> {role} at {company}')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--jd', help='job description text file; omit for the generic appendix')
    ap.add_argument('--base', default='https://takenbyninjas.com')
    ap.add_argument('--out', required=True)
    ap.add_argument('--name', help='how to name the JD in the nudge line (default: file name)')
    ap.add_argument('--tag', help='send tag ([a-z0-9-], as in the Link Tracker): the start URL becomes /for-agents/start/<tag>/ so fetches trace to this CV')
    ap.add_argument('--resp', help='re-render from a saved brief response (<out>.json from an earlier run): no paid call')
    ap.add_argument('--role', help='with --tag and --jd: the role title, written into for-agents/sends.json')
    ap.add_argument('--answer', action='append', default=[], metavar='TYPE=TEXT',
                    help="Tom's answer to a screening question for this job, e.g. location='onsite in Hørsholm: yes' (repeatable; kept with the tag in sends.json; ask him, never assume)")
    ap.add_argument('--company', help='with --tag and --jd: the company name')
    a = ap.parse_args()
    with open(ROWS_FILE, encoding='utf-8') as f:
        rows_json = json.load(f)
    resp = None
    jd_name = None
    if a.jd:
        jd_name = a.name or os.path.basename(a.jd).removesuffix('.txt')
        with open(a.jd, encoding='utf-8') as f:
            text = f.read()
        cache = a.out + '.json'
        if a.resp:
            with open(a.resp, encoding='utf-8') as f:
                resp = json.load(f)
        else:
            resp = post_brief(a.base, text)
            os.makedirs(os.path.dirname(a.out) or '.', exist_ok=True)
            with open(cache, 'w', encoding='utf-8') as f:
                json.dump(resp, f, ensure_ascii=False, indent=1)
        if resp.get('error'):
            print(f'brief failed: {resp["error"]}', file=sys.stderr)
            return 1
    # Name the JD as a person would: "<role> at <company>", else --name, else the file name.
    shown = a.name or (f'{a.role} at {a.company}' if a.role and a.company else jd_name)
    answers = {}
    if a.tag and os.path.exists(SENDS_FILE):
        with open(SENDS_FILE, encoding='utf-8') as f:
            answers = dict(json.load(f).get('sends', {}).get(a.tag, {}).get('answers') or {})
    for kv in a.answer:
        k, _, v = kv.partition('=')
        answers[k.strip()] = v.strip()
    out, open_q = build(resp, rows_json, shown, a.tag, applying=shown if (a.role and a.company) else None, answers=answers)
    os.makedirs(os.path.dirname(a.out) or '.', exist_ok=True)
    with open(a.out, 'w', encoding='utf-8') as f:
        f.write(out)
    if a.tag and resp is not None:
        record_send(a.tag, a.role, a.company, jd_name, answers)
    rows = (resp or {}).get('rows', [])
    print(f'{a.out}: {len(out.split())} words' + (f', {len(rows)} requirements, met {sum(r["met"] == "met" for r in rows)}, partial {sum(r["met"] == "partial" for r in rows)}, not met {sum(r["met"] == "not met" for r in rows)}' if rows else ''))
    # Application time (Tom, 2026-10-12): a screening question the record cannot
    # settle is put to Tom there and then, not printed as a gap and left.
    for q in open_q:
        print(f"ASK TOM [{q['type']}]: the job asks \"{one_line(q['asked'], 120)}\"; on record: {q['record'] or 'nothing'}. Re-run with --answer {q['type']}='...'")
    return 0


if __name__ == '__main__':
    sys.exit(main())
